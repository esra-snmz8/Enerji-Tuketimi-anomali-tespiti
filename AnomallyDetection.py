L2 = keras.regularizers.l2(1e-4)

class NHiTSBlock(layers.Layer):
    """N-HiTS Temel Bloğu: Pooling + Regülarize MLP + LayerNorm + Backcast/Forecast"""
    def __init__(self, units, num_layers, pool_size, backcast_length, forecast_length, drop=0.2, **kwargs):
        super().__init__(**kwargs)
        self.units = units
        self.num_layers = num_layers
        self.pool_size = pool_size
        self.backcast_length = backcast_length
        self.forecast_length = forecast_length
        self.drop = drop

        # N-HiTS: Multi-Rate Pooling
        self.pooling = layers.MaxPooling1D(pool_size=self.pool_size, padding='same') if self.pool_size and self.pool_size > 1 else None
        self.flatten = layers.Flatten()

        # MLP: Dense + LayerNorm + Dropout (L2 ile)
        self.mlp_layers = []
        for i in range(self.num_layers):
            self.mlp_layers += [
                layers.Dense(self.units, activation='relu', kernel_regularizer=L2, name=f'mlp_dense_{i}'),
                layers.LayerNormalization(name=f'ln_{i}'),
                layers.Dropout(self.drop, name=f'drop_{i}')
            ]

        # Basis Fonksiyonları (Regülarize edilmiş)
        self.theta_b = layers.Dense(self.backcast_length, kernel_regularizer=L2, name='theta_backcast')
        self.theta_f = layers.Dense(self.forecast_length, kernel_regularizer=L2, name='theta_forecast')

    def call(self, x, training=False):
        h = self.pooling(x) if self.pooling is not None else x
        h = self.flatten(h)
        for layer in self.mlp_layers:
            # Dropout sadece training modunda aktif olmalı
            h = layer(h, training=training) if isinstance(layer, layers.Dropout) else layer(h)

        # Backcast çıktısı (B, backcast_len, 1) şekline getirilir
        backcast = tf.expand_dims(self.theta_b(h), axis=-1)
        forecast = self.theta_f(h)
        return backcast, forecast

def build_nhits(backcast_len, forecast_len, n_feats,
                num_stacks=3, blocks_per_stack=2, num_layers=2, layer_size=128,
                pooling_sizes=(8,4,1), drop=0.2):
    """N-HiTS Çoklu Yığın Mimarisi"""
    inp = layers.Input(shape=(backcast_len, n_feats), name='input')
    residuals = inp
    forecasts = []

    # Hedef (ilk sütun) ve Dışsal (kalan) sütunları ayırma
    get_first = layers.Lambda(lambda t: t[:, :, 0:1])
    get_rest  = layers.Lambda(lambda t: t[:, :, 1:])

    for s in range(num_stacks):
        ps = pooling_sizes[s] if s < len(pooling_sizes) else 1
        for b in range(blocks_per_stack):
            blk = NHiTSBlock(layer_size, num_layers, ps, backcast_len, forecast_len, drop=drop, name=f'stack{s}_block{b}')
            backcast, forecast = blk(residuals)

            # Residual Connection: Backcast sadece hedef sütundan çıkarılır (Appliances)
            res_first = get_first(residuals)
            res_first = layers.Subtract()([res_first, backcast])

            # Diğer 14 özellik residual'a olduğu gibi eklenir (bağlamsal bilgi)
            if n_feats > 1:
                res_rest = get_rest(residuals)
                residuals = layers.Concatenate(axis=-1)([res_first, res_rest])
            else:
                residuals = res_first

            forecasts.append(forecast)

    out = layers.Add(name='ensemble')(forecasts) if len(forecasts) > 1 else forecasts[0]

    # 🌟 YENİLİK: Negatif Tahminleri Önlemek İçin ReLU Aktivasyonu
    out = layers.Activation('relu', name='relu_output')(out)

    return keras.Model(inp, out, name='NHiTS_V2')

