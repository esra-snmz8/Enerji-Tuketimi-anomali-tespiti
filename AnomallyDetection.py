def inverse_first(values):
    """RobustScaler ters dönüşümü ve Log ters dönüşümü (exp(x)-1)"""
    # values shape: (N, H) -> (N*H, 1) -> (N*H, 15)

    N_samples = values.shape[0]
    H = values.shape[1] if values.ndim > 1 else 1
    dummy = np.zeros((N_samples * H, len(feats)), dtype=np.float32)

    if values.ndim > 1:
        dummy[:, 0] = values.flatten()
    else:
        dummy[:, 0] = values

    # 1. Ters Ölçekleme (RobustScaler)
    scaled_inv = scaler.inverse_transform(dummy)[:, 0].reshape(N_samples, H)

    # 2. 🌟 YENİLİK: Log ters dönüşümü (exp(x) - 1)
    if LOG_TRANSFORM_TARGET:
        result_inv = np.expm1(scaled_inv)
    else:
        result_inv = scaled_inv

    # Negatif değerleri 0'a kısıtla (zaten ReLU ile kısıtlandı ama bu ekstra güvenlik)
    result_inv[result_inv < 0] = 0
    return result_inv

